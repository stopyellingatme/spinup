package db

import (
	"context"
	"database/sql"
	"fmt"
	"path"

	"github.com/pressly/goose/v3/lock"
)

// legacyKitProbe returns the schema check for an old kit version.
// Later kit versions never shared the app space and must not adopt app rows.
func legacyKitProbe(version int64) string {
	switch version {
	case 2:
		return "SELECT to_regclass('public.users') IS NOT NULL"
	case 3:
		return "SELECT to_regclass('public.password_resets') IS NOT NULL"
	case 4:
		return "SELECT to_regclass('public.user_identities') IS NOT NULL"
	case 5:
		return `SELECT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'users' AND column_name = 'role')`
	case 6:
		return "SELECT to_regclass('public.audit_events') IS NOT NULL"
	case 7:
		return `SELECT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'users' AND column_name = 'auth_version')`
	default:
		return ""
	}
}

// adopt moves legacy kit rows in one transaction under the goose advisory lock.
// Progress is printed after commit so a failed probe reports no adopted rows.
func (m *Migrator) adopt(ctx context.Context) error {
	if m.kitProvider == nil {
		return nil
	}
	tx, err := m.db.BeginTx(ctx, nil)
	if err != nil {
		return adoptionError(err)
	}
	defer func() { _ = tx.Rollback() }()
	if _, err := tx.ExecContext(ctx, "SELECT pg_advisory_xact_lock($1)", lock.DefaultLockID); err != nil {
		return adoptionError(err)
	}
	var exists bool
	if err := tx.QueryRowContext(ctx, "SELECT to_regclass('goose_db_version') IS NOT NULL").Scan(&exists); err != nil {
		return adoptionError(err)
	}
	if !exists {
		return adoptionError(tx.Commit())
	}
	if err := tx.QueryRowContext(ctx, "SELECT to_regclass('"+KitVersionTable+"') IS NOT NULL").Scan(&exists); err != nil {
		return adoptionError(err)
	}
	if !exists {
		// Keep the same DDL and zero row as the goose PostgreSQL store.
		if _, err := tx.ExecContext(ctx, `CREATE TABLE `+KitVersionTable+` (
   id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
   version_id bigint NOT NULL,
   is_applied boolean NOT NULL,
   tstamp timestamp NOT NULL DEFAULT now()
  )`); err != nil {
			return adoptionError(err)
		}
		if _, err := tx.ExecContext(ctx, "INSERT INTO "+KitVersionTable+" (version_id, is_applied) VALUES (0, true)"); err != nil {
			return adoptionError(err)
		}
	}
	var adopted []string
	for _, source := range m.kitProvider.ListSources() {
		probe := legacyKitProbe(source.Version)
		if probe == "" || m.HasVersion(source.Version) {
			continue
		}
		moved, err := adoptVersion(ctx, tx, source.Version, path.Base(source.Path), probe)
		if err != nil {
			return err
		}
		if moved {
			adopted = append(adopted, path.Base(source.Path))
		}
	}
	if err := tx.Commit(); err != nil {
		return adoptionError(err)
	}
	for _, name := range adopted {
		m.printf("adopted  kit %s\n", name)
	}
	return nil
}

func adoptVersion(ctx context.Context, tx *sql.Tx, version int64, name, probe string) (bool, error) {
	var kitExists, appApplied bool
	if err := tx.QueryRowContext(ctx, `SELECT
  EXISTS (SELECT 1 FROM `+KitVersionTable+` WHERE version_id = $1),
  EXISTS (SELECT 1 FROM goose_db_version WHERE version_id = $1 AND is_applied)`, version).Scan(&kitExists, &appApplied); err != nil {
		return false, adoptionError(err)
	}
	if kitExists || !appApplied {
		return false, nil
	}
	var found bool
	if err := tx.QueryRowContext(ctx, probe).Scan(&found); err != nil {
		return false, adoptionError(err)
	}
	if !found {
		return false, &userError{
			what: "migrate",
			why:  fmt.Sprintf("row %d in goose_db_version is not kit migration %s.", version, name),
			try:  fmt.Sprintf("renumber the app migration row by hand (UPDATE goose_db_version SET version_id = <app number> WHERE version_id = %d), then run migrate up again.", version),
		}
	}
	if _, err := tx.ExecContext(ctx, "INSERT INTO "+KitVersionTable+" (version_id, is_applied) VALUES ($1, true)", version); err != nil {
		return false, adoptionError(err)
	}
	if _, err := tx.ExecContext(ctx, "DELETE FROM goose_db_version WHERE version_id = $1", version); err != nil {
		return false, adoptionError(err)
	}
	return true, nil
}

func adoptionError(err error) error {
	if err == nil {
		return nil
	}
	return &userError{what: "migrate", why: "adopt kit migrations: " + err.Error(), try: "fix the database error, then run migrate up again", err: err}
}
