//! Embeds the converted packs (`packs/`) and the Rust-only overlay (`overlay/`) in the
//! crate (ADR 0020 §3). Main loop only.
//!
//! The script writes `$OUT_DIR/embedded.rs` with two sorted static lists, `PACKS` and
//! `OVERLAY`, of `(path, bytes)` pairs. Unit R1.7 includes it in `embed`:
//!
//! ```ignore
//! include!(concat!(env!("OUT_DIR"), "/embedded.rs"));
//! ```
//!
//! File modes come from `pack.toml`, as in Go, so the lists hold no modes. The `.gitkeep`
//! file at the top of each directory is not embedded.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let manifest =
        PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR")).join("embedded.rs");
    let mut code = String::from("// Generated by build.rs. Do not edit.\n");
    for (name, dir, doc) in [
        (
            "PACKS",
            "packs",
            "The converted packs, by path below `packs/`.",
        ),
        (
            "OVERLAY",
            "overlay",
            "The Rust-only overlay, by path below `overlay/`.",
        ),
    ] {
        let root = manifest.join(dir);
        println!("cargo::rerun-if-changed={}", root.display());
        writeln!(code, "/// {doc}\npub static {name}: &[(&str, &[u8])] = &[").expect("write");
        for (path, file) in files(&root) {
            writeln!(
                code,
                "    ({path:?}, include_bytes!({:?})),",
                file.display()
            )
            .expect("write");
        }
        code.push_str("];\n");
    }
    std::fs::write(&out, code).expect("write embedded.rs");
}

/// Returns the regular files below `root` as (slash path, absolute path), sorted by path.
fn files(root: &Path) -> Vec<(String, PathBuf)> {
    if !root.is_dir() {
        return Vec::new();
    }
    let mut files = Vec::new();
    for entry in walkdir::WalkDir::new(root).sort_by_file_name() {
        let entry = entry.expect("walk the pack directory");
        if !entry.file_type().is_file() {
            continue;
        }
        let rel = entry
            .path()
            .strip_prefix(root)
            .expect("path below the root");
        let path: Vec<&str> = rel
            .components()
            .map(|c| c.as_os_str().to_str().expect("pack paths are UTF-8"))
            .collect();
        let path = path.join("/");
        if path == ".gitkeep" {
            continue;
        }
        files.push((path, entry.path().to_path_buf()));
    }
    files.sort();
    files
}
