//! Rebuild resource navigation from disk and planned paths.
#[cfg(test)]
mod tests;
use anyhow::{Context, Result, bail};
use spinup_manifest::lock::Lock;
use spinup_vfs::plan::{File, Plan};
use std::{
    collections::{BTreeMap, BTreeSet},
    path::Path,
};

const NAV: &str = "web/src/lib/nav.gen.ts";

/// Plans navigation after additions or removals of resource pages.
///
/// # Errors
/// Returns an error if a route cannot be read or navigation is already planned.
pub fn plan_nav(root: &Path, mut plan: Plan, removed: &[String]) -> Result<Plan> {
    if !crate::pages::exists(root, "spinup.lock")? {
        return Ok(plan);
    }
    let lock = Lock::load(root.join("spinup.lock"))?;
    if !lock.packs.iter().any(|p| p == "web")
        || crate::pages::answer(&lock, "frontend_mode").as_deref() == Some("embed")
    {
        return Ok(plan);
    }
    let removed: BTreeSet<&str> = removed
        .iter()
        .map(String::as_str)
        .chain(
            plan.files
                .iter()
                .filter(|f| f.delete)
                .map(|f| f.path.as_str()),
        )
        .collect();
    let mut routes: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    let mut add = |path: &str| {
        if removed.contains(path) {
            return;
        }
        let Some((route, name)) = path
            .strip_prefix("web/src/routes/")
            .and_then(|p| p.split_once('/'))
        else {
            return;
        };
        if !route.is_empty() && ["+page.svelte", "schema.ts", "form.ts"].contains(&name) {
            routes.entry(route.into()).or_default().insert(name.into());
        }
    };
    let dir = root.join("web/src/routes");
    if crate::pages::exists(root, "web/src/routes")? {
        for entry in std::fs::read_dir(&dir)
            .context("read web routes failed\nTry: check the web route directory")?
        {
            let entry =
                entry.context("read web route failed\nTry: check the web route directory")?;
            if !entry
                .file_type()
                .context("inspect web route failed\nTry: check the web route directory")?
                .is_dir()
            {
                continue;
            }
            for file in std::fs::read_dir(entry.path())
                .context("read web route failed\nTry: check the web route directory")?
            {
                let file =
                    file.context("read web route failed\nTry: check the web route directory")?;
                if !file
                    .file_type()
                    .context("inspect web route failed\nTry: check the web route directory")?
                    .is_dir()
                {
                    add(&format!(
                        "web/src/routes/{}/{}",
                        entry.file_name().to_string_lossy(),
                        file.file_name().to_string_lossy()
                    ));
                }
            }
        }
    }
    for file in plan.files.iter().filter(|f| !f.delete) {
        add(&file.path);
    }
    let mut source = "// Code generated by spinup. DO NOT EDIT.\nexport type NavItem = { href: string; label: string };\nexport const nav: NavItem[] = [\n".to_string();
    let mut home = "/".to_string();
    for (route, files) in routes {
        if files.contains("+page.svelte")
            && (files.contains("schema.ts") || files.contains("form.ts"))
        {
            if home == "/" {
                home = format!("/{route}");
            }
            let label = route
                .replace('-', " ")
                .split_whitespace()
                .map(crate::pages::capitalize)
                .collect::<Vec<_>>()
                .join(" ");
            source.push_str(&format!("\t{{ href: '/{route}', label: '{label}' }},\n"));
        }
    }
    source.push_str(&format!("];\nexport const home: string = '{home}';\n"));
    if plan.get(NAV).is_some() {
        bail!("rebuild navigation: {NAV} is already planned\nTry: report this generator bug");
    }
    plan.add(File {
        path: NAV.into(),
        data: source.into_bytes(),
        class: "managed".into(),
        ..File::default()
    })?;
    Ok(plan.sorted())
}
