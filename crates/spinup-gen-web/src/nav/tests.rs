//! Navigation reflects disk content, planned content, and deletions.
use super::*;

#[test]
#[allow(
    clippy::disallowed_methods,
    reason = "Build temporary route fixtures for navigation tests."
)]
fn nav_paths_add_remove_sort_and_skip() -> Result<()> {
    let root = tempfile::tempdir()?;
    let mut lock = Lock::new();
    lock.packs.push("web".into());
    lock.save(root.path().join("spinup.lock"))?;
    for (route, names) in [
        ("zebras", vec!["+page.svelte", "form.ts"]),
        ("blog-posts", vec!["+page.svelte", "schema.ts"]),
        ("manual", vec!["+page.svelte"]),
        ("nested/ignore", vec!["+page.svelte", "schema.ts"]),
    ] {
        let dir = root.path().join("web/src/routes").join(route);
        std::fs::create_dir_all(&dir)?;
        for name in names {
            std::fs::write(dir.join(name), "fixture")?;
        }
    }
    let mut plan = Plan::new();
    for path in [
        "web/src/routes/apples/+page.svelte",
        "web/src/routes/apples/schema.ts",
    ] {
        plan.add(File {
            path: path.into(),
            ..File::default()
        })?;
    }
    let result = plan_nav(root.path(), plan.clone(), &[])?;
    let file = result.get(NAV).unwrap();
    assert_eq!(file.class, "managed");
    assert_eq!(
        String::from_utf8(file.data)?,
        "// Code generated by spinup. DO NOT EDIT.\nexport type NavItem = { href: string; label: string };\nexport const nav: NavItem[] = [\n\t{ href: '/apples', label: 'Apples' },\n\t{ href: '/blog-posts', label: 'Blog Posts' },\n\t{ href: '/zebras', label: 'Zebras' },\n];\nexport const home: string = '/apples';\n"
    );
    plan.add(File {
        path: "web/src/routes/zebras/form.ts".into(),
        delete: true,
        ..File::default()
    })?;
    let result = plan_nav(
        root.path(),
        plan,
        &[
            "web/src/routes/blog-posts/+page.svelte".into(),
            "web/src/routes/apples/schema.ts".into(),
        ],
    )?;
    assert_eq!(
        String::from_utf8(result.get(NAV).unwrap().data)?,
        "// Code generated by spinup. DO NOT EDIT.\nexport type NavItem = { href: string; label: string };\nexport const nav: NavItem[] = [\n];\nexport const home: string = '/';\n"
    );
    let mut conflict = Plan::new();
    conflict.add(File {
        path: NAV.into(),
        ..File::default()
    })?;
    assert!(
        plan_nav(root.path(), conflict, &[])
            .unwrap_err()
            .to_string()
            .contains("already planned")
    );
    lock.answers.insert(
        "frontend_mode".into(),
        serde_json::value::RawValue::from_string("\"embed\"".into())?,
    );
    lock.save(root.path().join("spinup.lock"))?;
    assert!(plan_nav(root.path(), Plan::new(), &[])?.files.is_empty());
    lock.packs.clear();
    lock.save(root.path().join("spinup.lock"))?;
    assert!(plan_nav(root.path(), Plan::new(), &[])?.files.is_empty());
    let missing = tempfile::tempdir()?;
    assert!(plan_nav(missing.path(), Plan::new(), &[])?.files.is_empty());
    Ok(())
}
