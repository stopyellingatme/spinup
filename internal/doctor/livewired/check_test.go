func TestAliasedImports(t *testing.T) {
	source := strings.NewReplacer(
		`applive "example.com/demo/api/internal/live"`, `feeds "example.com/demo/api/internal/live"`,
		`"github.com/stopyellingatme/spinup/kit/app"`, `kitapp "github.com/stopyellingatme/spinup/kit/app"`,
		`kitlive "github.com/stopyellingatme/spinup/kit/x/live"`, `rt "github.com/stopyellingatme/spinup/kit/x/live"`,
		"applive.", "feeds.",
		"kitlive.", "rt.",
		"app.", "kitapp.",
		"liveHub", "hub",
	).Replace(wired)
	if got := checkWiring([]byte(source)); got.Status != doctor.OK {
		t.Fatalf("%+v\n%s", got, source)
	}
	// The default names do not match after the alias.
	broken := strings.Replace(source, "rt.IsStream", "kitlive.IsStream", 1)
	if got := checkWiring([]byte(broken)); got.Status != doctor.Warn || !strings.Contains(got.Message, "kitapp.WithRequestTimeoutExempt(rt.IsStream)") {
		t.Fatalf("%+v", got)
	}
}

