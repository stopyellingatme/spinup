func writeLock(t *testing.T, root string, packs ...string) {
	t.Helper()
	lock := manifest.New()
	lock.Packs = packs
	if err := lock.Save(filepath.Join(root, "spinup.lock")); err != nil {
		t.Fatal(err)
	}
}

func writeFile(t *testing.T, root, path, data string) {
	t.Helper()
	full := filepath.Join(root, path)
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(full, []byte(data), 0o644); err != nil {
		t.Fatal(err)
	}
}

const wired = `package main

import (
	"context"

	applive "example.com/demo/api/internal/live"
	"github.com/stopyellingatme/spinup/kit/app"
	kitlive "github.com/stopyellingatme/spinup/kit/x/live"
)

func run(ctx context.Context) error {
	liveHub, err := kitlive.New(pool,
		kitlive.WithMaxStreams(liveEnv.MaxStreams),
		kitlive.WithMaxStreamsPerUser(liveEnv.MaxStreamsPerUser),
	)
	if err != nil {
		return err
	}
	if err := liveHub.Start(ctx); err != nil {
		return err
	}
	a := app.New(
		app.WithRequestTimeoutExempt(kitlive.IsStream),
		app.WithRoutes(applive.Routes(liveHub, applive.Deps{DB: pool})),
		app.WithCommand("live", liveHub.Command()),
		app.WithReadiness("live", liveHub.Ready),
		app.WithDrain(liveHub.Drain),
		app.WithShutdown(func(context.Context) error { pool.Close(); return nil }),
		app.WithShutdown(liveHub.Close),
	)
	return a.Run(ctx, nil)
}
`

const feedFile = `package live

import (
	"net/http"

	kitlive "github.com/stopyellingatme/spinup/kit/x/live"
)

const notesFeed = "notes"

// spinup:live-feed notes registerNotesFeed
func registerNotesFeed(mux *http.ServeMux, h *kitlive.Hub, d Deps) {
	_ = kitlive.SharedKey(notesFeed)
}
`

const generated = `// Code generated by spinup. DO NOT EDIT.

package live

func registerGenerated(mux *http.ServeMux, h *kitlive.Hub, d Deps) {
	registerNotesFeed(mux, h, d)
}
`

const handler = `package handlers

import "github.com/stopyellingatme/spinup/kit/x/live"

func (s *Server) create(ctx context.Context, tx pgx.Tx, user auth.User) error {
	return live.Publish(ctx, tx, live.OwnedKey("notes", user.ID), live.Upsert("1", nil))
}
`

// project writes a wired app with one feed and returns its root.
func project(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	writeLock(t, root, "base", "api", "web", "auth", "live")
	writeFile(t, root, mainPath, wired)
	writeFile(t, root, migrationPath, "-- +goose Up\n")
	writeFile(t, root, "api/internal/live/live.go", "package live\n")
	writeFile(t, root, "api/internal/live/notes.go", feedFile)
	writeFile(t, root, "api/internal/live/feeds_gen.go", generated)
	writeFile(t, root, "api/internal/handlers/notes.go", handler)
	return root
}

func run(t *testing.T, root string) doctor.Result {
	t.Helper()
	return runCheck(t.Context(), &doctor.Context{Root: root})
}

