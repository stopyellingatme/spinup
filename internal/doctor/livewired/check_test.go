func TestMissingLines(t *testing.T) {
	for _, tc := range []struct {
		name, old, new, want string
	}{
		{"no app import", `applive "example.com/demo/api/internal/live"`, `"fmt"`, lineImportApp},
		{"no kit import", `kitlive "github.com/stopyellingatme/spinup/kit/x/live"`, `"fmt"`, lineImportKit},
		{"no New binding", "liveHub, err := kitlive.New(pool,", "_, err = kitlive.New(pool,", "liveHub, err := kitlive.New(pool,"},
		{"no Start", "if err := liveHub.Start(ctx); err != nil {", "if err := liveHub.Ready(ctx); err != nil {", "liveHub.Start(ctx)"},
		{"no Routes", "app.WithRoutes(applive.Routes(liveHub, applive.Deps{DB: pool})),", "", "app.WithRoutes(applive.Routes(liveHub, applive.Deps{DB: pool})),"},
		{"no exempt", "app.WithRequestTimeoutExempt(kitlive.IsStream),", "", "app.WithRequestTimeoutExempt(kitlive.IsStream),"},
		{"other exempt", "app.WithRequestTimeoutExempt(kitlive.IsStream),", "app.WithRequestTimeoutExempt(isExport),", "app.WithRequestTimeoutExempt(kitlive.IsStream),"},
		{"no drain", "app.WithDrain(liveHub.Drain),", "", "app.WithDrain(liveHub.Drain),"},
		{"no shutdown", "app.WithShutdown(liveHub.Close),", "", "app.WithShutdown(liveHub.Close),"},
		{"Routes outside app.New", "app.WithRoutes(applive.Routes(liveHub, applive.Deps{DB: pool})),", "", "app.WithRoutes(applive.Routes("},
	} {
		t.Run(tc.name, func(t *testing.T) {
			source := strings.Replace(wired, tc.old, tc.new, 1)
			if tc.name == "Routes outside app.New" {
				source = strings.Replace(source, "return a.Run(ctx, nil)", "_ = applive.Routes(liveHub, applive.Deps{DB: pool})\n\treturn a.Run(ctx, nil)", 1)
			}
			if source == wired {
				t.Fatal("the fixture did not change")
			}
			got := checkWiring([]byte(source))
			if got.Status != doctor.Warn || !strings.Contains(got.Try, tc.want) || !strings.Contains(got.Message, mainPath) || !strings.HasSuffix(got.Try, docsHint) {
				t.Fatalf("%+v", got)
			}
		})
	}
}

