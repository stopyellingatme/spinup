package templates_test

import (
	"errors"
	"io/fs"
	"strings"
	"testing"

	"github.com/stopyellingatme/spinup/internal/testutil"
)

// TestWebShell checks the app shell of ADR 0015 §3 with and without the auth module, and in embed mode.
func TestWebShell(t *testing.T) {
	t.Parallel()
	const nav = "// Code generated by spinup. DO NOT EDIT.\n" +
		"export type NavItem = { href: string; label: string };\n" +
		"export const nav: NavItem[] = [];\n" +
		"export const home: string = '/';\n"
	for _, tc := range []struct {
		name    string
		packs   []string
		answers map[string]any
		// present and absent list files of the rendered tree.
		present, absent []string
		// layoutHas and layoutLacks list strings of web/src/routes/+layout.svelte.
		layoutHas, layoutLacks []string
	}{
		{
			name:        "no auth",
			packs:       []string{"base", "api", "web"},
			answers:     map[string]any{"app_name": "todo", "module": "example.com/todo", "modules": "ci"},
			present:     []string{"web/src/routes/+error.svelte", "web/src/lib/components/app/field.svelte"},
			absent:      []string{"web/src/routes/+page.server.ts", "web/src/lib/components/app/user-menu.svelte"},
			layoutHas:   []string{"<Toaster richColors closeButton />", "const shell = true;"},
			layoutLacks: []string{"/login", "UserMenu", "data.user"},
		},
		{
			name:      "auth",
			packs:     []string{"base", "api", "web", "auth"},
			answers:   map[string]any{"app_name": "todo", "module": "example.com/todo", "modules": "ci,auth"},
			present:   []string{"web/src/routes/+error.svelte", "web/src/routes/+page.server.ts", "web/src/lib/components/app/user-menu.svelte"},
			layoutHas: []string{"<Toaster richColors closeButton />", `<UserMenu email={data.user.email} />`, `href="/login"`, "data.user !== null"},
		},
		{
			name:        "embed",
			packs:       []string{"base", "api", "web"},
			answers:     map[string]any{"app_name": "todo", "module": "example.com/todo", "modules": "ci", "frontend_mode": "embed"},
			present:     []string{"web/src/routes/+error.svelte", "web/src/routes/+layout.ts"},
			absent:      []string{"web/src/routes/+page.server.ts", "web/src/routes/+layout.server.ts", "web/src/lib/components/app/user-menu.svelte"},
			layoutHas:   []string{"<Toaster richColors closeButton />", "<TopBar "},
			layoutLacks: []string{"/login", "data.user"},
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			tree := testutil.RenderPack(t, tc.packs, tc.answers)
			got, err := fs.ReadFile(tree, "web/src/lib/nav.gen.ts")
			if err != nil {
				t.Fatal(err)
			}
			if string(got) != nav {
				t.Errorf("web/src/lib/nav.gen.ts = %q, want %q", got, nav)
			}
			for _, name := range tc.present {
				if _, err := fs.Stat(tree, name); err != nil {
					t.Errorf("missing %s: %v", name, err)
				}
			}
			for _, name := range tc.absent {
				if _, err := fs.Stat(tree, name); !errors.Is(err, fs.ErrNotExist) {
					t.Errorf("unexpected %s: %v", name, err)
				}
			}
			layout, err := fs.ReadFile(tree, "web/src/routes/+layout.svelte")
			if err != nil {
				t.Fatal(err)
			}
			for _, want := range tc.layoutHas {
				if !strings.Contains(string(layout), want) {
					t.Errorf("+layout.svelte lacks %q", want)
				}
			}
			for _, unwanted := range tc.layoutLacks {
				if strings.Contains(string(layout), unwanted) {
					t.Errorf("+layout.svelte has %q", unwanted)
				}
			}
		})
	}
}
