func TestRolesAndForce(t *testing.T) {
	in := input(t, "tool", "lookup_order")
	write(t, in.Root, "spinup.toml", "name = 'demo'\n")
	write(t, in.Root, "api/internal/mcp/lookup_order.go", "package mcp\n// spinup:mcp-tool registerPrevious\nfunc registerPrevious() {}\n")
	if err := in.Flags.Parse([]string{"--role", "manager", "--role", "staff", "--force"}); err != nil {
		t.Fatal(err)
	}
	out, err := plan(t.Context(), in)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(out.Plan.Files[0].Data), `Roles:       []string{"manager", "staff"}`) {
		t.Fatalf("missing roles:\n%s", out.Plan.Files[0].Data)
	}
	if strings.Contains(string(out.Plan.Files[1].Data), "registerPrevious") {
		t.Fatal("force retained the old marker")
	}
	disk, err := os.ReadFile(filepath.Join(in.Root, "api/internal/mcp/lookup_order.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(disk), "registerPrevious") {
		t.Fatal("planning changed the source file")
	}
	if len(out.Edits) != 1 || out.Edits[0] != GeneratedPath {
		t.Fatal("managed registration requires an edit")
	}
}
