func TestToolNames(t *testing.T) {
	for _, name := range []string{"lookup_order", "a", "a2", strings.Repeat("a", 64)} {
		if _, err := toolName(name); err != nil {
			t.Errorf("%s: %v", name, err)
		}
	}
	for _, name := range []string{"", "Lookup", "bad-name", "_a", "a__b", "a_", "2a", strings.Repeat("a", 65), "generated", "whoami", "server"} {
		if _, err := toolName(name); err == nil || !strings.Contains(err.Error(), "Try:") {
			t.Errorf("%q: %v", name, err)
		}
	}
}

func TestRenderGenerated(t *testing.T) {
	root := t.TempDir()
	dir := filepath.Join(root, "api/internal/mcp")
	if err := os.MkdirAll(filepath.Join(dir, "nested"), 0755); err != nil {
		t.Fatal(err)
	}
	for path, src := range map[string]string{
		"z.go":             "package mcp\n// spinup:mcp-tool registerZulu\nfunc registerZulu() {}\n",
		"a.go":             "package mcp\n// spinup:mcp-tool registerAlpha\nfunc registerAlpha() {}\n",
		"nested/ignore.go": "// spinup:mcp-tool registerIgnore\n",
		"ignore.txt":       "// spinup:mcp-tool registerIgnore\n",
	} {
		if err := os.WriteFile(filepath.Join(dir, path), []byte(src), 0644); err != nil {
			t.Fatal(err)
		}
	}
	file, err := RenderGenerated(root, []vfs.File{{Path: "api/internal/mcp/a.go", Data: []byte("package mcp\n// spinup:mcp-tool registerBeta\nfunc registerBeta() {}\n")}})
	if err != nil {
		t.Fatal(err)
	}
	want := `// Code generated by spinup. DO NOT EDIT.

package mcp

import kitmcp "github.com/stopyellingatme/spinup/kit/x/mcp"

func registerGenerated(s *kitmcp.Server, d Deps) {
	registerBeta(s, d)
	registerZulu(s, d)
}
`
	if string(file.Data) != want {
		t.Fatalf("got:\n%s\nwant:\n%s", file.Data, want)
	}
}

func input(t *testing.T, args ...string) gen.Input {
	t.Helper()
	fs := pflag.NewFlagSet("mcp", pflag.ContinueOnError)
	flags(fs)
	fs.Bool("force", false, "")
	return gen.Input{Root: t.TempDir(), Args: args, Flags: fs, Lock: &manifest.Lock{Packs: []string{"mcp"}}}
}

func TestPlanErrors(t *testing.T) {
	for _, tc := range []struct {
		name   string
		change func(*gen.Input)
		want   string
	}{
		{"usage", func(in *gen.Input) { in.Args = nil }, "Try: spinup g mcp tool"},
		{"module", func(in *gen.Input) { in.Lock = nil }, "Try: spinup module add mcp"},
		{"exists", func(in *gen.Input) { write(t, in.Root, "api/internal/mcp/lookup_order.go", "package mcp") }, "Try: pass --force"},
		{"role", func(in *gen.Input) {
			write(t, in.Root, "spinup.toml", "name = 'demo'\n")
			if err := in.Flags.Set("role", "absent"); err != nil {
				t.Fatal(err)
			}
		}, "Try: use one of:"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			in := input(t, "tool", "lookup_order")
			tc.change(&in)
			_, err := plan(context.Background(), in)
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("%v, want %s", err, tc.want)
			}
		})
	}
}

func write(t *testing.T, root, path, src string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(filepath.Join(root, path)), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, path), []byte(src), 0644); err != nil {
		t.Fatal(err)
	}
}

func TestToolSource(t *testing.T) {
	in := input(t, "tool", "lookup_order")
	out, err := plan(t.Context(), in)
	if err != nil {
		t.Fatal(err)
	}
	want := `package mcp

import (
	"context"

	kitmcp "github.com/stopyellingatme/spinup/kit/x/mcp"
)

// LookupOrderIn holds the tool arguments.
type LookupOrderIn struct{}

// LookupOrderOut holds the tool result.
type LookupOrderOut struct{}

// spinup:mcp-tool registerLookupOrder
func registerLookupOrder(s *kitmcp.Server, d Deps) {
	kitmcp.Tool(s, kitmcp.ToolDef{
		Name:        "lookup_order",
		Description: "Runs lookup order.",
		ReadOnly:    true,
		Destructive: false,
		Roles:       []string(nil),
	}, func(ctx context.Context, in LookupOrderIn) (LookupOrderOut, error) {
		return LookupOrderOut{}, kitmcp.ToolError("not implemented")
	})
}
`
	if string(out.Plan.Files[0].Data) != want {
		t.Fatalf("source =\n%s\nwant:\n%s", out.Plan.Files[0].Data, want)
	}
	for _, flag := range []string{"write", "destructive"} {
		t.Run(flag, func(t *testing.T) {
			in := input(t, "tool", "lookup_order")
			if err := in.Flags.Set(flag, "true"); err != nil {
				t.Fatal(err)
			}
			out, err := plan(t.Context(), in)
			if err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(string(out.Plan.Files[0].Data), "ReadOnly:    false") {
				t.Fatal("write tool is read-only")
			}
			if flag == "destructive" && !strings.Contains(string(out.Plan.Files[0].Data), "Destructive: true") {
				t.Fatal("missing destructive hint")
			}
		})
	}
}

