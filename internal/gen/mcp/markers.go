package mcp

import (
	"fmt"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/stopyellingatme/spinup/internal/manifest"
	"github.com/stopyellingatme/spinup/internal/vfs"
)

var marker = regexp.MustCompile(`^// spinup:mcp-tool (register[A-Z][A-Za-z0-9]*)$`)

// RenderGenerated scans direct Go files and applies pending replacements before rendering registrations.
func RenderGenerated(root string, pending []vfs.File) (vfs.File, error) {
	paths, err := filepath.Glob(filepath.Join(root, "api/internal/mcp/*.go"))
	if err != nil {
		return vfs.File{}, fmt.Errorf("cannot scan MCP tools: %w\nTry: check api/internal/mcp", err)
	}
	sources := make(map[string][]byte)
	for _, path := range paths {
		rel := "api/internal/mcp/" + filepath.Base(path)
		if rel == GeneratedPath {
			continue
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return vfs.File{}, fmt.Errorf("cannot read %s: %w\nTry: check the file permissions", rel, err)
		}
		sources[rel] = data
	}
	for _, file := range pending {
		if filepath.ToSlash(filepath.Dir(file.Path)) == "api/internal/mcp" && strings.HasSuffix(file.Path, ".go") && file.Path != GeneratedPath {
			sources[file.Path] = file.Data
		}
	}
	keys := make([]string, 0, len(sources))
	for path := range sources {
		keys = append(keys, path)
	}
	slices.Sort(keys)
	var names []string
	for _, path := range keys {
		file, err := parser.ParseFile(token.NewFileSet(), path, sources[path], parser.ParseComments)
		if err != nil {
			return vfs.File{}, fmt.Errorf("cannot scan MCP tool %s: %w\nTry: correct the Go source", path, err)
		}
		for _, group := range file.Comments {
			for _, comment := range group.List {
				match := marker.FindStringSubmatch(comment.Text)
				if match == nil {
					continue
				}
				name := match[1]
				if slices.Contains(names, name) {
					return vfs.File{}, fmt.Errorf("cannot register MCP tool: duplicate marker %s\nTry: give each tool a unique registration function", name)
				}
				names = append(names, name)
			}
		}
	}
	slices.Sort(names)
	var src strings.Builder
	src.WriteString("// Code generated by spinup. DO NOT EDIT.\n\npackage mcp\n\nimport kitmcp \"github.com/stopyellingatme/spinup/kit/x/mcp\"\n\nfunc registerGenerated(s *kitmcp.Server, d Deps) {\n")
	for _, name := range names {
		fmt.Fprintf(&src, "%s(s, d)\n", name)
	}
	src.WriteString("}\n")
	data, err := format.Source([]byte(src.String()))
	if err != nil {
		return vfs.File{}, fmt.Errorf("cannot format MCP registrations: %w\nTry: correct the tool markers", err)
	}
	return vfs.File{Path: GeneratedPath, Data: data, Class: string(manifest.Managed)}, nil
}
