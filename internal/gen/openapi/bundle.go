package openapi

import (
	"bytes"
	"cmp"
	"errors"
	"fmt"
	"io"
	"net/url"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"go.yaml.in/yaml/v3"
)

const bundleHeader = "# Code generated by spinup from api/openapi/. DO NOT EDIT.\n"

type reference struct{ file, value string }

// Bundle merges the root OpenAPI document and sorted path and schema fragments.
// apiDir is the application's api directory. All references must resolve locally.
func Bundle(apiDir string) ([]byte, error) {
	data, err := bundle(apiDir)
	if err != nil {
		return nil, fmt.Errorf("cannot bundle OpenAPI: %w\nTry: correct the files in api/openapi/, then run spinup g openapi", err)
	}
	return data, nil
}

func bundle(apiDir string) ([]byte, error) {
	rootFile := "openapi/openapi.yaml"
	root, err := readMap(apiDir, rootFile)
	if err != nil {
		return nil, err
	}
	paths, err := object(root, "paths", rootFile)
	if err != nil {
		return nil, err
	}
	components, err := object(root, "components", rootFile)
	if err != nil {
		return nil, err
	}
	schemas, err := object(components, "schemas", rootFile)
	if err != nil {
		return nil, err
	}
	var refs []reference
	if err := references(root, rootFile, &refs); err != nil {
		return nil, err
	}
	for _, group := range []struct {
		dir    string
		target map[string]any
	}{
		{"paths", paths}, {"schemas", schemas},
	} {
		owners := make(map[string]string)
		for key := range group.target {
			owners[key] = rootFile
		}
		files, err := os.ReadDir(filepath.Join(apiDir, "openapi", group.dir))
		if err != nil && !os.IsNotExist(err) {
			return nil, fmt.Errorf("list openapi/%s: %w", group.dir, err)
		}
		// ReadDir returns filenames in lexical order.
		for _, file := range files {
			if !strings.HasSuffix(file.Name(), ".yaml") {
				continue
			}
			rel := "openapi/" + group.dir + "/" + file.Name()
			fragment, err := readMap(apiDir, rel)
			if err != nil {
				return nil, err
			}
			if err := references(fragment, rel, &refs); err != nil {
				return nil, err
			}
			for _, key := range sortedKeys(fragment) {
				if first, exists := owners[key]; exists {
					return nil, fmt.Errorf("duplicate %s key %q in %s and %s", group.dir, key, first, rel)
				}
				group.target[key] = fragment[key]
				owners[key] = rel
			}
		}
	}
	for _, ref := range refs {
		if !resolves(root, ref.value) {
			return nil, fmt.Errorf("%s: $ref %q does not resolve", ref.file, ref.value)
		}
	}
	var out bytes.Buffer
	out.WriteString(bundleHeader)
	encoder := yaml.NewEncoder(&out)
	encoder.SetIndent(2)
	var document yaml.Node
	if err := document.Encode(root); err != nil {
		return nil, fmt.Errorf("encode bundle: %w", err)
	}
	sortMappings(&document)
	if err := encoder.Encode(&document); err != nil {
		return nil, fmt.Errorf("encode bundle: %w", err)
	}
	if err := encoder.Close(); err != nil {
		return nil, fmt.Errorf("close bundle encoder: %w", err)
	}
	return out.Bytes(), nil
}

func sortMappings(node *yaml.Node) {
	if node.Kind == yaml.MappingNode {
		pairs := make([][2]*yaml.Node, 0, len(node.Content)/2)
		for i := 0; i < len(node.Content); i += 2 {
			pairs = append(pairs, [2]*yaml.Node{node.Content[i], node.Content[i+1]})
		}
		slices.SortFunc(pairs, func(a, b [2]*yaml.Node) int { return cmp.Compare(a[0].Value, b[0].Value) })
		for i, pair := range pairs {
			node.Content[2*i], node.Content[2*i+1] = pair[0], pair[1]
		}
	}
	for _, child := range node.Content {
		sortMappings(child)
	}
}

func readMap(apiDir, file string) (map[string]any, error) {
	data, err := os.ReadFile(filepath.Join(apiDir, filepath.FromSlash(file)))
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", file, err)
	}
	decoder := yaml.NewDecoder(bytes.NewReader(data))
	var value any
	if err := decoder.Decode(&value); err != nil {
		return nil, fmt.Errorf("read %s: %w", file, err)
	}
	var extra any
	if err := decoder.Decode(&extra); !errors.Is(err, io.EOF) {
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", file, err)
		}
		return nil, fmt.Errorf("%s: expected one YAML document", file)
	}
	m, ok := value.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("%s: expected a map with string keys", file)
	}
	return m, nil
}

func object(parent map[string]any, key, file string) (map[string]any, error) {
	value, exists := parent[key]
	if !exists {
		value = map[string]any{}
		parent[key] = value
	}
	m, ok := value.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("%s: %s must be a map with string keys", file, key)
	}
	return m, nil
}

func sortedKeys(m map[string]any) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	return keys
}

func references(value any, file string, refs *[]reference) error {
	switch value := value.(type) {
	case map[string]any:
		for _, key := range sortedKeys(value) {
			if key == "$ref" {
				ref, ok := value[key].(string)
				if !ok || !strings.HasPrefix(ref, "#/components/") {
					return fmt.Errorf("%s: $ref %v must be local (#/components/...)", file, value[key])
				}
				*refs = append(*refs, reference{file, ref})
			}
			if err := references(value[key], file, refs); err != nil {
				return err
			}
		}
	case []any:
		for _, item := range value {
			if err := references(item, file, refs); err != nil {
				return err
			}
		}
	case map[any]any:
		return fmt.Errorf("%s: map keys must be strings", file)
	}
	return nil
}

func resolves(root map[string]any, ref string) bool {
	pointer, err := url.PathUnescape(strings.TrimPrefix(ref, "#"))
	if err != nil {
		return false
	}
	var current any = root
	for _, token := range strings.Split(strings.TrimPrefix(pointer, "/"), "/") {
		for i := 0; i < len(token); i++ {
			if token[i] == '~' {
				if i+1 == len(token) || token[i+1] != '0' && token[i+1] != '1' {
					return false
				}
				i++
			}
		}
		// Decode JSON Pointer escapes in this order (RFC 6901).
		token = strings.ReplaceAll(strings.ReplaceAll(token, "~1", "/"), "~0", "~")
		switch value := current.(type) {
		case map[string]any:
			var exists bool
			current, exists = value[token]
			if !exists {
				return false
			}
		case []any:
			index, err := strconv.Atoi(token)
			if err != nil || index < 0 || index >= len(value) || strconv.Itoa(index) != token {
				return false
			}
			current = value[index]
		default:
			return false
		}
	}
	return true
}
