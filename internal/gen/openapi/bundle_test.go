const rootSpec = `openapi: 3.0.3
info: {title: todo, version: 0.1.0}
servers: [{url: /}]
paths: {}
components:
  schemas:
    Problem: {type: object}
`

func put(t *testing.T, api, path, data string) {
	t.Helper()
	name := filepath.Join(api, filepath.FromSlash(path))
	if err := os.MkdirAll(filepath.Dir(name), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(name, []byte(data), 0644); err != nil {
		t.Fatal(err)
	}
}

func TestBundle(t *testing.T) {
	t.Parallel()
	api := t.TempDir()
	put(t, api, "openapi/openapi.yaml", rootSpec)
	put(t, api, "openapi/paths/z.yaml", "/z: {get: {responses: {'200': {description: OK}}}}\n")
	put(t, api, "openapi/schemas/numbered.yaml", "Schema2: {type: string}\nSchema10: {type: string}\n")
	put(t, api, "openapi/paths/a.yaml", "/a: {get: {responses: {'200': {description: OK, content: {application/json: {schema: {$ref: '#/components/schemas/Todo'}}}}}}}\n")
	put(t, api, "openapi/schemas/todo.yaml", "Todo: {type: object, properties: {title: {type: string}, error: {$ref: '#/components/schemas/Problem'}}}\n")
	put(t, api, "openapi/paths/.gitkeep", "")
	put(t, api, "openapi/paths/ignored.txt", "invalid")
	got, err := Bundle(api)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.HasPrefix(got, []byte("# Code generated by spinup from api/openapi/. DO NOT EDIT.\n")) {
		t.Fatalf("header: %s", got)
	}
	if bytes.Index(got, []byte("  /a:")) > bytes.Index(got, []byte("  /z:")) {
		t.Fatalf("path order: %s", got)
	}
	if bytes.Index(got, []byte("    Problem:")) > bytes.Index(got, []byte("    Todo:")) {
		t.Fatalf("schema order: %s", got)
	}
	if bytes.Index(got, []byte("    Schema10:")) > bytes.Index(got, []byte("    Schema2:")) {
		t.Fatalf("keys must use lexical order: %s", got)
	}
	var doc map[string]any
	if err := yaml.Unmarshal(got, &doc); err != nil {
		t.Fatal(err)
	}
	if len(doc["paths"].(map[string]any)) != 2 {
		t.Fatalf("paths: %s", got)
	}
	again, err := Bundle(api)
	if err != nil || !bytes.Equal(got, again) {
		t.Fatalf("not deterministic: %v", err)
	}
}

func TestBundleErrors(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name, root string
		files      map[string]string
		want       []string
	}{
		{name: "missing root", want: []string{"openapi/openapi.yaml"}},
		{name: "duplicate paths", root: rootSpec, files: map[string]string{"paths/a.yaml": "/todos: {}", "paths/b.yaml": "/todos: {}"}, want: []string{"/todos", "paths/a.yaml", "paths/b.yaml"}},
		{name: "root path duplicate", root: strings.Replace(rootSpec, "paths: {}", "paths: {'/todos': {}}", 1), files: map[string]string{"paths/todos.yaml": "/todos: {}"}, want: []string{"/todos", "openapi.yaml", "paths/todos.yaml"}},
		{name: "duplicate schema", root: rootSpec, files: map[string]string{"schemas/problem.yaml": "Problem: {}"}, want: []string{"Problem", "openapi.yaml", "schemas/problem.yaml"}},
		{name: "fragment schema duplicate", root: rootSpec, files: map[string]string{"schemas/a.yaml": "Todo: {}", "schemas/b.yaml": "Todo: {}"}, want: []string{"Todo", "schemas/a.yaml", "schemas/b.yaml"}},
		{name: "external ref", root: rootSpec, files: map[string]string{"schemas/todo.yaml": "Todo: {$ref: 'other.yaml#/Todo'}"}, want: []string{"schemas/todo.yaml", "other.yaml#/Todo", "local"}},
		{name: "remote ref", root: rootSpec, files: map[string]string{"paths/todos.yaml": "/todos: {$ref: 'https://example.com/spec'}"}, want: []string{"paths/todos.yaml", "local"}},
		{name: "missing ref", root: rootSpec, files: map[string]string{"schemas/todo.yaml": "Todo: {$ref: '#/components/schemas/Missing'}"}, want: []string{"schemas/todo.yaml", "Missing", "resolve"}},
		{name: "root ref", root: rootSpec + "x-test: {$ref: '#/components/schemas/Missing'}\n", want: []string{"openapi.yaml", "Missing"}},
		{name: "invalid pointer escape", root: rootSpec + "x-test: {$ref: '#/components/schemas/Problem~2'}\n", want: []string{"openapi.yaml", "resolve"}},
		{name: "invalid percent escape", root: rootSpec + "x-test: {$ref: '#/components/schemas/Problem%ZZ'}\n", want: []string{"openapi.yaml", "resolve"}},
		{name: "noncomponent ref", root: rootSpec + "x-test: {$ref: '#/info'}\n", want: []string{"openapi.yaml", "local"}},
		{name: "nonstring ref", root: rootSpec, files: map[string]string{"schemas/a.yaml": "Todo: {$ref: 4}"}, want: []string{"schemas/a.yaml", "$ref"}},
		{name: "bad yaml", root: rootSpec, files: map[string]string{"paths/broken.yaml": "/todos: ["}, want: []string{"paths/broken.yaml"}},
		{name: "sequence fragment", root: rootSpec, files: map[string]string{"paths/broken.yaml": "- /todos"}, want: []string{"paths/broken.yaml", "map"}},
		{name: "duplicate yaml key", root: rootSpec, files: map[string]string{"schemas/a.yaml": "Todo: {}\nTodo: {}"}, want: []string{"schemas/a.yaml", "already defined"}},
		{name: "cyclic alias", root: rootSpec, files: map[string]string{"schemas/a.yaml": "Todo: &todo {child: *todo}"}, want: []string{"schemas/a.yaml", "cyclic"}},
		{name: "invalid merge", root: rootSpec, files: map[string]string{"schemas/a.yaml": "Todo: {<<: 4}"}, want: []string{"schemas/a.yaml", "merge"}},
		{name: "complex key", root: rootSpec, files: map[string]string{"schemas/a.yaml": "? [a, b]\n: {}"}, want: []string{"schemas/a.yaml", "keys"}},
		{name: "normalized duplicate key", root: rootSpec, files: map[string]string{"paths/a.yaml": "/todos: {get: {responses: {200: {}, '200': {}}}}"}, want: []string{"paths/a.yaml", "already defined"}},
		{name: "extra document", root: rootSpec + "---\npaths: {}\n", want: []string{"openapi.yaml", "document"}},
		{name: "invalid paths", root: strings.Replace(rootSpec, "paths: {}", "paths: []", 1), want: []string{"openapi.yaml", "paths", "map"}},
		{name: "invalid components", root: strings.Replace(rootSpec, "components:\n  schemas:\n    Problem: {type: object}", "components: []", 1), want: []string{"openapi.yaml", "components", "map"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			api := t.TempDir()
			if tc.root != "" {
				put(t, api, "openapi/openapi.yaml", tc.root)
			}
			for name, data := range tc.files {
				put(t, api, "openapi/"+name, data)
			}
			_, err := Bundle(api)
			if err == nil {
				t.Fatal("expected an error")
			}
			for _, want := range append(tc.want, "\nTry:") {
				if !strings.Contains(err.Error(), want) {
					t.Errorf("%v does not contain %q", err, want)
				}
			}
		})
	}
}

func TestBundleEmptyAndComponentRefs(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct{ name, extra string }{
		{"empty", ""},
		{"escaped pointer", "    A/B~C: {type: string}\n    Ref: {$ref: '#/components/schemas/A~1B~0C'}\n"},
		{"percent encoded pointer", "    A B: {type: string}\n    Ref: {$ref: '#/components/schemas/A%20B'}\n"},
		{"recursive schema", "    Recursive: {type: object, properties: {child: {$ref: '#/components/schemas/Recursive'}}}\n"},
		{"cross fragment", "    Ref: {$ref: '#/components/schemas/Todo'}\n"},
		{"array pointer", "    Ref: {$ref: '#/components/schemas/Todo/required/0'}\n"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			api := t.TempDir()
			put(t, api, "openapi/openapi.yaml", rootSpec+tc.extra)
			if tc.name != "empty" {
				put(t, api, "openapi/schemas/todo.yaml", "Todo: {type: object, required: [id], properties: {id: {type: integer}}}")
			}
			got, err := Bundle(api)
			if err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(string(got), "paths: {}") {
				t.Fatalf("empty paths: %s", got)
			}
		})
	}
}

func TestBundleNumericResponseKeys(t *testing.T) {
	t.Parallel()
	for _, location := range []string{"root", "fragment"} {
		t.Run(location, func(t *testing.T) {
			t.Parallel()
			api := t.TempDir()
			path := "/things:\n  get:\n    responses:\n      200:\n        description: OK\n        content:\n          application/json:\n            schema: {$ref: '#/components/schemas/Problem'}\n      404: {description: Missing}\n"
			root := rootSpec
			if location == "root" {
				root = strings.Replace(root, "paths: {}", "paths:\n"+indentYAML(path, "  "), 1)
			} else {
				put(t, api, "openapi/paths/things.yaml", path)
			}
			put(t, api, "openapi/openapi.yaml", root)
			got, err := Bundle(api)
			if err != nil {
				t.Fatal(err)
			}
			for _, code := range []string{"200", "404"} {
				if !bytes.Contains(got, []byte(`"`+code+`":`)) {
					t.Errorf("response key %s must be quoted:\n%s", code, got)
				}
			}
			again, err := Bundle(api)
			if err != nil || !bytes.Equal(got, again) {
				t.Fatalf("bundle is not deterministic: %v", err)
			}
		})
	}
}

func TestBundlePreservesScalarTextAndTags(t *testing.T) {
	t.Parallel()
	for _, location := range []string{"root", "fragment"} {
		for _, tc := range []struct{ value, tag string }{
			{"2001-01-01", "!!timestamp"},
			{"0123", "!!int"},
			{"1e3", "!!float"},
		} {
			t.Run(location+"/"+tc.value, func(t *testing.T) {
				t.Parallel()
				api := t.TempDir()
				schema := "Sample:\n  type: string\n  format: date\n  example: " + tc.value + "\n  default: " + tc.value + "\n  enum: [" + tc.value + "]\n"
				root := rootSpec
				if location == "root" {
					root += indentYAML(schema, "    ")
				} else {
					put(t, api, "openapi/schemas/sample.yaml", schema)
				}
				put(t, api, "openapi/openapi.yaml", root)
				got, err := Bundle(api)
				if err != nil {
					t.Fatal(err)
				}
				var doc yaml.Node
				if err := yaml.Unmarshal(got, &doc); err != nil {
					t.Fatal(err)
				}
				sample := yamlAt(t, doc.Content[0], "components", "schemas", "Sample")
				for _, field := range []string{"example", "default", "enum"} {
					node := yamlAt(t, sample, field)
					if field == "enum" {
						node = node.Content[0]
					}
					if node.Value != tc.value || node.Tag != tc.tag {
						t.Errorf("%s: got (%q, %q), want (%q, %q)", field, node.Value, node.Tag, tc.value, tc.tag)
					}
				}
			})
		}
	}
}

func indentYAML(text, indent string) string {
	return indent + strings.ReplaceAll(strings.TrimSuffix(text, "\n"), "\n", "\n"+indent) + "\n"
}

func yamlAt(t *testing.T, node *yaml.Node, keys ...string) *yaml.Node {
	t.Helper()
	for _, key := range keys {
		var found *yaml.Node
		for i := 0; i < len(node.Content); i += 2 {
			if node.Content[i].Value == key {
				found = node.Content[i+1]
				break
			}
		}
		if found == nil {
			t.Fatalf("missing YAML key %q", key)
		}
		node = found
	}
	return node
}

func TestBundleYAMLAliasesAndMerges(t *testing.T) {
	t.Parallel()
	api := t.TempDir()
	put(t, api, "openapi/openapi.yaml", rootSpec)
	put(t, api, "openapi/schemas/aliases.yaml", `ZBase: &base
  type: string
  default: 0123
Alias: *base
Merged:
  <<: *base
  default: 1e3
Ref: {$ref: '#/components/schemas/Merged/type'}
`)
	got, err := Bundle(api)
	if err != nil {
		t.Fatal(err)
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(got, &doc); err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct{ name, value string }{{"Alias", "0123"}, {"Merged", "1e3"}} {
		node := yamlAt(t, doc.Content[0], "components", "schemas", tc.name, "default")
		if node.Value != tc.value {
			t.Errorf("%s default: got %q, want %q", tc.name, node.Value, tc.value)
		}
	}
}
