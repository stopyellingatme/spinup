package resource

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"

	"github.com/stopyellingatme/spinup/internal/manifest"
	"github.com/stopyellingatme/spinup/internal/vfs"
)

const navPath = "web/src/lib/nav.gen.ts"

// PlanNav adds the generated navigation file for the resource page folders.
// Removed contains paths that the caller will remove before it applies plan.
func PlanNav(root string, plan vfs.Plan, removed []string) (vfs.Plan, error) {
	web, err := hasWeb(root)
	if err != nil || !web {
		return plan, err
	}
	lock, err := manifest.Load(filepath.Join(root, "spinup.lock"))
	if err != nil {
		return vfs.Plan{}, err
	}
	if lock.Answers["frontend_mode"] == "embed" {
		return plan, nil
	}

	files, err := navRouteFiles(root, plan, removed)
	if err != nil {
		return vfs.Plan{}, err
	}
	items := make([]navItem, 0, len(files))
	for route, names := range files {
		if names["+page.svelte"] && (names["schema.ts"] || names["form.ts"]) {
			items = append(items, navItem{href: "/" + route, label: navLabel(route)})
		}
	}
	sort.Slice(items, func(i, j int) bool { return items[i].href < items[j].href })
	data := navSource(items)
	if _, ok := plan.Get(navPath); ok {
		return vfs.Plan{}, fmt.Errorf("rebuild navigation: %s is already planned\nTry: report this generator bug", navPath)
	}
	if err := plan.Add(vfs.File{Path: navPath, Data: data, Class: string(manifest.Managed)}); err != nil {
		return vfs.Plan{}, err
	}
	return plan.Sorted(), nil
}

type navItem struct {
	href  string
	label string
}

func navRouteFiles(root string, plan vfs.Plan, removed []string) (map[string]map[string]bool, error) {
	removedSet := make(map[string]bool, len(removed))
	for _, path := range removed {
		removedSet[path] = true
	}
	for _, file := range plan.Files {
		if file.Delete {
			removedSet[file.Path] = true
		}
	}

	routes := make(map[string]map[string]bool)
	routesDir := filepath.Join(root, "web", "src", "routes")
	entries, err := os.ReadDir(routesDir)
	if errors.Is(err, os.ErrNotExist) {
		return routes, nil
	}
	if err != nil {
		return nil, fmt.Errorf("read web routes: %w\nTry: check the web route directory", err)
	}
	for _, entry := range entries {
		if !entry.IsDir() {
			continue
		}
		routeEntries, err := os.ReadDir(filepath.Join(routesDir, entry.Name()))
		if err != nil {
			return nil, fmt.Errorf("read web route %s: %w\nTry: check the web route directory", entry.Name(), err)
		}
		for _, routeEntry := range routeEntries {
			if routeEntry.IsDir() {
				continue
			}
			path := "web/src/routes/" + entry.Name() + "/" + routeEntry.Name()
			if !removedSet[path] {
				addNavRouteFile(routes, entry.Name(), routeEntry.Name())
			}
		}
	}
	for _, file := range plan.Files {
		if file.Delete || removedSet[file.Path] {
			continue
		}
		route, name, ok := navRoutePath(file.Path)
		if ok {
			addNavRouteFile(routes, route, name)
		}
	}
	return routes, nil
}

func navRoutePath(path string) (string, string, bool) {
	const prefix = "web/src/routes/"
	if !strings.HasPrefix(path, prefix) {
		return "", "", false
	}
	rest := strings.TrimPrefix(path, prefix)
	route, name, ok := strings.Cut(rest, "/")
	if !ok || strings.Contains(name, "/") || route == "" {
		return "", "", false
	}
	return route, name, true
}

func addNavRouteFile(routes map[string]map[string]bool, route, name string) {
	if name != "+page.svelte" && name != "schema.ts" && name != "form.ts" {
		return
	}
	if routes[route] == nil {
		routes[route] = make(map[string]bool)
	}
	routes[route][name] = true
}

func navLabel(route string) string {
	words := strings.Fields(strings.ReplaceAll(route, "-", " "))
	for i, word := range words {
		runes := []rune(word)
		if len(runes) > 0 {
			runes[0] = unicode.ToUpper(runes[0])
			words[i] = string(runes)
		}
	}
	return strings.Join(words, " ")
}

func navSource(items []navItem) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by spinup. DO NOT EDIT.\n")
	b.WriteString("export type NavItem = { href: string; label: string };\n")
	b.WriteString("export const nav: NavItem[] = [\n")
	for _, item := range items {
		fmt.Fprintf(&b, "\t{ href: '%s', label: '%s' },\n", item.href, item.label)
	}
	b.WriteString("];\n")
	home := "/"
	if len(items) > 0 {
		home = items[0].href
	}
	fmt.Fprintf(&b, "export const home: string = '%s';\n", home)
	return []byte(b.String())
}
