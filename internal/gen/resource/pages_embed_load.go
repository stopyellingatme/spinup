package resource

// The browser loads and the form helpers of the pages in embed mode (ADR 0039
// §10.5). The Go binary serves a single-page app, so every load runs in the
// browser and calls the Go API on the same origin. With the auth module, each
// load awaits the root load and runs the guard before any API call. The Go API
// checks the session, the role, the owner, and the values of every call.

const embedFormTS = `// The browser helpers of the [[ .Words ]] pages: the dependency key, the id of a route, the read of
// one [[ .Words ]], and the mapping of an API problem to a form. The pages call the Go API from the
// browser with the typed client. The Go API checks every call.
// Generated by spinup g resource. The application owns this file.
import { error } from '@sveltejs/kit';
import { setError, setMessage, type ErrorStatus, type FormPathLeavesWithErrors, type SuperValidated } from 'sveltekit-superforms';
import { api } from '#lib/api/client.js';
[[- if .Auth ]]
import { observedFetch } from '#lib/session-watch.js';
[[- end ]]
import { problemMessage, type Item, type Problem, type Values } from './schema';

/** RESOURCE_DEP is the dependency key of the [[ .Words ]] data. A write or a live patch invalidates it. */
export const RESOURCE_DEP = '[[ .Dep ]]';

/**
 * unreachable is the message when a request to the Go API did not complete: the network failed, or
 * the request was aborted. The API client throws then, so each caller catches and shows this text.
 */
export const unreachable = 'The server did not answer. Check the connection and try again.';

/** notFound is the text of the 404 view of a [[ .Words ]]. */
export const notFound = 'This [[ .Words ]] does not exist.';

/** id reads a [[ .Words ]] id. It returns 0 when the value is not a positive whole number. */
export function id(value: string | null): number {
	const n = Number(value);
	return Number.isSafeInteger(n) && n > 0 ? n : 0;
}

/**
 * getItem returns a [[ .Words ]], or shows the 404 view when it does not exist[[ if .Auth ]] or the API hides it from
 * this user[[ end ]]. A request that does not complete shows a page error, and a reload tries again.
 */
export async function getItem(fetch: typeof globalThis.fetch, param: string): Promise<Item> {
	const path = { id: id(param) };
	if (path.id === 0) error(404, notFound);
	const { data, error: problem, response } = await api
		.GET('[[ .APIPath ]]/{id}', { [[ if .Auth ]]fetch: observedFetch(fetch)[[ else ]]fetch[[ end ]], params: { path } })
		.catch((err: unknown): never => {
			console.error('[[ .Feed ]]: the read failed:', err);
			error(503, unreachable);
		});
	if (response.status === 404) error(404, notFound);
	if (!data) error(response.status, problemMessage(problem, response.status));
	return data;
}

/**
 * applyFailure puts an API problem on the form: each field error at its input, any other problem
 * as the form message. It marks the form invalid, so superforms keeps the values.
 */
export function applyFailure(form: SuperValidated<Values>, problem: Problem | undefined, status: number): void {
	const code = (status >= 400 && status <= 599 ? status : 500) as ErrorStatus;
	const errors = (problem?.errors ?? []).filter((e) => e.field in form.data);
	if (errors.length === 0) {
		setMessage(form, problemMessage(problem, status), { status: code });
		return;
	}
	for (const e of errors) {
		setError(form, e.field as FormPathLeavesWithErrors<Values>, e.message, { status: code });
	}
}
`

const embedListTS = `import { error, redirect } from '@sveltejs/kit';
import { api } from '#lib/api/client.js';
[[- if .Roles ]]
import { requireRole } from '#lib/auth.js';
[[- else if .Auth ]]
import { requireUser } from '#lib/auth.js';
[[- end ]]
[[- if .Auth ]]
import { observedFetch } from '#lib/session-watch.js';
[[- end ]]
import { RESOURCE_DEP, unreachable } from './form';
import { problemMessage } from './schema';
import type { PageLoad } from './$types';

/** The number of [[ .PluralWords ]] on one page of the list. */
const perPage = 20;

// pageNumber reads ?page=. A missing or invalid value is the first page.
function pageNumber(value: string | null): number {
	const n = Number(value);
	return Number.isSafeInteger(n) && n > 0 ? n : 1;
}

export const load: PageLoad = async ({ fetch, [[ if .Auth ]]parent, [[ end ]]url, depends }) => {
	depends(RESOURCE_DEP);
[[- if .Auth ]]
	const { user } = await parent();
[[- end ]]
[[- if .Roles ]]
	requireRole(user, url, [[ .RoleLiterals ]]);
[[- else if .Auth ]]
	requireUser(user, url);
[[- end ]]
	const page = pageNumber(url.searchParams.get('page'));
	const { data, error: problem, response } = await api
		.GET('[[ .APIPath ]]', {
			[[ if .Auth ]]fetch: observedFetch(fetch)[[ else ]]fetch[[ end ]],
			params: { query: { limit: perPage, offset: (page - 1) * perPage } }
		})
		.catch((err: unknown): never => {
			console.error('[[ .Feed ]]: the list read failed:', err);
			error(503, unreachable);
		});
	if (!data) error(response.status, problemMessage(problem, response.status));
	const pages = Math.max(1, Math.ceil(data.total / perPage));
	if (page > pages) {
		// The page is past the end, for example after a delete: show the last page.
		const last = new URL(url);
		last.searchParams.set('page', String(pages));
		redirect(303, last.pathname + last.search);
	}
	return { items: data.items, total: data.total, page, perPage };
};
`

