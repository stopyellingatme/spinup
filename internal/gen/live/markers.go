package live

import (
	"fmt"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/stopyellingatme/spinup/internal/manifest"
	"github.com/stopyellingatme/spinup/internal/vfs"
)

var marker = regexp.MustCompile(`^// spinup:live-feed ([a-z][a-z0-9_]{0,47}) (register[A-Z][A-Za-z0-9]*)$`)

// Feed identifies a feed marker and its source file.
type Feed struct {
	// Name is the feed name.
	Name string
	// Func is the registration function.
	Func string
	// File is the path relative to the project root.
	File string
}

// ScanFeeds reads feed markers, applies pending files, and sorts by feed name.
func ScanFeeds(root string, pending []vfs.File) ([]Feed, error) {
	paths, err := filepath.Glob(filepath.Join(root, Dir, "*.go"))
	if err != nil {
		return nil, fmt.Errorf("cannot scan live feeds: %w\nTry: check %s", err, Dir)
	}
	sources := map[string][]byte{}
	for _, path := range paths {
		rel := Dir + "/" + filepath.Base(path)
		if rel == GeneratedPath {
			continue
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return nil, fmt.Errorf("cannot read %s: %w\nTry: check the file permissions", rel, err)
		}
		sources[rel] = data
	}
	for _, file := range pending {
		path := filepath.ToSlash(file.Path)
		if filepath.ToSlash(filepath.Dir(path)) == Dir && strings.HasSuffix(path, ".go") && path != GeneratedPath {
			sources[path] = file.Data
		}
	}
	paths = paths[:0]
	for path := range sources {
		paths = append(paths, path)
	}
	slices.Sort(paths)
	var feeds []Feed
	names, funcs := map[string]bool{}, map[string]bool{}
	for _, path := range paths {
		file, err := parser.ParseFile(token.NewFileSet(), path, sources[path], parser.ParseComments)
		if err != nil {
			return nil, fmt.Errorf("cannot scan live feed %s: %w\nTry: correct the Go source", path, err)
		}
		for _, group := range file.Comments {
			for _, comment := range group.List {
				match := marker.FindStringSubmatch(comment.Text)
				if match == nil {
					continue
				}
				if names[match[1]] || funcs[match[2]] {
					return nil, fmt.Errorf("cannot register live feed: duplicate marker %s %s\nTry: give each feed a unique name and registration function", match[1], match[2])
				}
				names[match[1]], funcs[match[2]] = true, true
				feeds = append(feeds, Feed{Name: match[1], Func: match[2], File: path})
			}
		}
	}
	slices.SortFunc(feeds, func(a, b Feed) int { return strings.Compare(a.Name, b.Name) })
	return feeds, nil
}

// RenderGenerated renders the managed registrations from disk and pending files.
func RenderGenerated(root string, pending []vfs.File) (vfs.File, error) {
	feeds, err := ScanFeeds(root, pending)
	if err != nil {
		return vfs.File{}, err
	}
	var src strings.Builder
	src.WriteString("// Code generated by spinup. DO NOT EDIT.\n\npackage live\n\nimport (\n\"net/http\"\n\nkitlive \"github.com/stopyellingatme/spinup/kit/x/live\"\n)\n\nfunc registerGenerated(mux *http.ServeMux, h *kitlive.Hub, d Deps) {\n")
	for _, feed := range feeds {
		fmt.Fprintf(&src, "%s(mux, h, d)\n", feed.Func)
	}
	src.WriteString("}\n")
	data, err := format.Source([]byte(src.String()))
	if err != nil {
		return vfs.File{}, fmt.Errorf("cannot format live registrations: %w\nTry: correct the feed markers", err)
	}
	return vfs.File{Path: GeneratedPath, Data: data, Class: string(manifest.Managed)}, nil
}
