package apicompat

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const (
	kitDir       = "../../kit"
	baselinePath = "../../kit/api/current.txt"
	minorPath    = "../../kit/api/minor.txt"
)

func updating() bool { return os.Getenv("SPINUP_GOLDEN_UPDATE") == "1" }

func writeBaseline(t *testing.T, lines []string) {
	t.Helper()
	header := "# Kit public API baseline. Generated by `SPINUP_GOLDEN_UPDATE=1 go test ./internal/apicompat`.\n# See docs/policy/kit-compat.md.\n"
	if err := os.WriteFile(baselinePath, []byte(header+strings.Join(lines, "\n")+"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestKitAPI(t *testing.T) {
	current, err := Extract(kitDir)
	if err != nil {
		t.Fatal(err)
	}
	baseline, err := ReadLines(baselinePath)
	if err != nil {
		t.Fatal(err)
	}
	minor, err := ReadMinor(minorPath)
	if err != nil {
		t.Fatal(err)
	}
	diff := Compare(baseline, current, minor)
	if updating() {
		if diff.Breaking() && os.Getenv("SPINUP_API_BREAK") != "1" {
			t.Fatalf("refusing to rewrite the baseline over a breaking change\n%s", diff.Message())
		}
		writeBaseline(t, current)
		return
	}
	if !diff.Clean() {
		if diff.Breaking() || len(diff.Added)+len(diff.Marked) > 0 {
			t.Fatalf("kit API differs from kit/api/current.txt\n%s", diff.Message())
		}
		t.Logf("allowed removals are pending in the baseline\n%s", diff.Message())
	}
}

func TestExtractFixture(t *testing.T) {
	got, err := Extract("testdata/api")
	if err != nil {
		t.Fatal(err)
	}
	want, err := ReadLines("testdata/api.golden")
	if err != nil {
		t.Fatal(err)
	}
	if updating() {
		if err := os.WriteFile("testdata/api.golden", []byte(strings.Join(got, "\n")+"\n"), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Fatalf("Extract() mismatch\ngot:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
	for _, line := range got {
		if strings.Contains(line, "hidden") || strings.Contains(line, "/internal") || strings.Contains(line, "/x") {
			t.Errorf("unexported or excluded API leaked: %s", line)
		}
	}
}

func TestCompare(t *testing.T) {
	base := []string{
		"kit/a func Keep(int) error",
		"kit/a func Gone(int) error",
		"kit/a func Edit(int) error",
		"kit/a func OldDep(int) error deprecated:v0.3",
		"kit/a func NewDep(int) error deprecated:v0.8",
		"kit/a type Old struct deprecated:v0.3",
		"kit/a field Old.F string",
		"kit/a func Mark() error",
	}
	cur := []string{
		"kit/a func Keep(int) error",
		"kit/a func Edit(string) error",
		"kit/a func Add()",
		"kit/a func Mark() error deprecated:v0.8",
	}
	d := Compare(base, cur, 8)
	check := func(name string, got []string, want ...string) {
		t.Helper()
		if strings.Join(got, "|") != strings.Join(want, "|") {
			t.Errorf("%s = %q, want %q", name, got, want)
		}
	}
	check("Removed", d.Removed, "kit/a func Gone(int) error", "kit/a func NewDep(int) error deprecated:v0.8")
	check("Changed", d.Changed, "kit/a func Edit(int) error  =>  kit/a func Edit(string) error")
	check("Added", d.Added, "kit/a func Add()")
	check("Marked", d.Marked, "kit/a func Mark() error  =>  kit/a func Mark() error deprecated:v0.8")
	check("Allowed", d.Allowed, "kit/a func OldDep(int) error deprecated:v0.3", "kit/a type Old struct deprecated:v0.3", "kit/a field Old.F string")
	if !d.Breaking() || d.Clean() {
		t.Error("diff must be breaking")
	}
	msg := d.Message()
	if !strings.Contains(msg, "Gone") || !strings.Contains(msg, "Try:") {
		t.Errorf("Message() = %q", msg)
	}
	if !Compare(cur, cur, 8).Clean() {
		t.Error("identical APIs must be clean")
	}
	if Compare(base, base, 8).Clean() == false {
		t.Error("identical baseline must be clean")
	}
}

func TestSplitKeys(t *testing.T) {
	for line, want := range map[string]string{
		"kit/a func F[T any](T) T":              "kit/a func F",
		"kit/a ptrmethod S.Do(int) error":       "kit/a ptrmethod S.Do",
		"kit/a field S.X map[string]int":        "kit/a field S.X",
		"kit/a const C int = 1 deprecated:v0.2": "kit/a const C",
		"kit/a type G[K comparable] struct":     "kit/a type G",
	} {
		if got, _, _ := split(line); got != want {
			t.Errorf("split(%q) key = %q, want %q", line, got, want)
		}
	}
}

func TestReadMinor(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "minor.txt")
	for text, want := range map[string]int{"0.8\n": 8, "v0.12": 12} {
		if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
		if got, err := ReadMinor(path); err != nil || got != want {
			t.Errorf("ReadMinor(%q) = %d, %v", text, got, err)
		}
	}
	if err := os.WriteFile(path, []byte("1.2"), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := ReadMinor(path); err == nil || !strings.Contains(err.Error(), "Try:") {
		t.Errorf("ReadMinor(1.2) error = %v", err)
	}
}

func TestDeprecationFixtures(t *testing.T) {
	good, err := CheckDeprecations("testdata/lint/good")
	if err != nil || len(good) != 0 {
		t.Fatalf("good fixtures: %v, %v", good, err)
	}
	bad, err := CheckDeprecations("testdata/lint/bad")
	if err != nil {
		t.Fatal(err)
	}
	var all []string
	for _, p := range bad {
		all = append(all, p.String())
	}
	text := strings.Join(all, "\n")
	for _, want := range []string{`"Deprecated: Use New instead."`, `"Deprecated: since v0.2 use New."`, "deprecated function Forward ", `"Deprecated: since v0.3. Use New instead"`} {
		if !strings.Contains(text, want) {
			t.Errorf("missing problem %s in\n%s", want, text)
		}
	}
	if len(bad) != 4 {
		t.Errorf("got %d problems, want 4:\n%s", len(bad), text)
	}
}

