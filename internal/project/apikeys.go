package project

import (
	"errors"
	"fmt"
	"go/format"
	"regexp"
	"slices"
	"strings"
)

// Paths of the files that spinup g apikeys writes (ADR 0030 decision 3).
const (
	APIKeysFilePath   = "api/internal/apikeys/apikeys.gen.go"
	APIKeysTSFilePath = "web/src/lib/apikeys.gen.ts"
)

// Defaults of the [apikeys] table (ADR 0030 decision 2.2).
const (
	DefaultAPIKeyPrefix  = "key"
	DefaultAPIKeyPlan    = "free"
	DefaultAPIKeyMaxKeys = 10
)

// APIKeyPlan is one [apikeys.plans.<name>] table of spinup.toml.
type APIKeyPlan struct {
	PerMinute int `toml:"per_minute"`
	PerDay    int `toml:"per_day"`
}

// APIKeysDecl is the [apikeys] table of spinup.toml.
type APIKeysDecl struct {
	Prefix      string                `toml:"prefix"`
	DefaultPlan string                `toml:"default_plan"`
	MaxKeys     int                   `toml:"max_keys"`
	Plans       map[string]APIKeyPlan `toml:"plans"`
}

// APIKeysConfig returns the [apikeys] table with the defaults of ADR 0030
// decision 2.2 applied. It does not change c.
func (c *Config) APIKeysConfig() APIKeysDecl {
	d := c.APIKeys
	if d.Prefix == "" {
		d.Prefix = DefaultAPIKeyPrefix
	}
	if d.DefaultPlan == "" {
		d.DefaultPlan = DefaultAPIKeyPlan
	}
	if d.MaxKeys == 0 {
		d.MaxKeys = DefaultAPIKeyMaxKeys
	}
	plans := make(map[string]APIKeyPlan, max(1, len(d.Plans)))
	for name, plan := range d.Plans {
		plans[name] = plan
	}
	if len(plans) == 0 {
		plans[DefaultAPIKeyPlan] = APIKeyPlan{PerMinute: 60, PerDay: 1000}
	}
	d.Plans = plans
	return d
}

// PlanNames returns the plan names in sorted order.
func (d APIKeysDecl) PlanNames() []string {
	names := make([]string, 0, len(d.Plans))
	for name := range d.Plans {
		names = append(names, name)
	}
	slices.Sort(names)
	return names
}

var (
	apiKeyPrefixPattern = regexp.MustCompile(`^[a-z][a-z0-9]{1,15}$`)
	apiKeyPlanPattern   = regexp.MustCompile(`^[a-z][a-z0-9_]{0,31}$`)
)

const apiKeysHint = "\nTry: correct [apikeys] in spinup.toml and run spinup g apikeys."

// Validate checks the rules of ADR 0030 decision 2.3. Call it on the result of
// APIKeysConfig, so that the defaults are applied.
func (d APIKeysDecl) Validate() error {
	var problems []error
	fail := func(format string, args ...any) {
		problems = append(problems, fmt.Errorf("apikeys: "+format+apiKeysHint, args...))
	}
	if !apiKeyPrefixPattern.MatchString(d.Prefix) {
		fail("the prefix %q does not match %s", d.Prefix, apiKeyPrefixPattern.String())
	}
	if d.MaxKeys < 1 || d.MaxKeys > 100 {
		fail("max_keys %d must be 1 to 100", d.MaxKeys)
	}
	if len(d.Plans) < 1 || len(d.Plans) > 16 {
		fail("the plan count %d must be 1 to 16", len(d.Plans))
	}
	for _, name := range d.PlanNames() {
		plan := d.Plans[name]
		switch {
		case !apiKeyPlanPattern.MatchString(name):
			fail("the plan name %q does not match %s", name, apiKeyPlanPattern.String())
		case plan.PerMinute < 1 || plan.PerMinute > 100000:
			fail("plan %q: per_minute %d must be 1 to 100000", name, plan.PerMinute)
		case plan.PerDay < 1 || plan.PerDay > 100000000:
			fail("plan %q: per_day %d must be 1 to 100000000", name, plan.PerDay)
		case plan.PerDay < plan.PerMinute:
			fail("plan %q: per_day %d must be at least per_minute %d", name, plan.PerDay, plan.PerMinute)
		}
	}
	if _, ok := d.Plans[d.DefaultPlan]; !ok {
		fail("default_plan %q is not a declared plan (declared: %s)", d.DefaultPlan, strings.Join(d.PlanNames(), ", "))
	}
	return errors.Join(problems...)
}

// RenderAPIKeysFile returns the formatted Go source of api/internal/apikeys/apikeys.gen.go.
// d must be valid (the result of APIKeysConfig with no Validate error).
func RenderAPIKeysFile(d APIKeysDecl) []byte {
	if err := d.Validate(); err != nil {
		panic(err)
	}
	var out strings.Builder
	out.WriteString("// Code generated by spinup. DO NOT EDIT.\n\npackage apikeys\n\nimport kitapikeys \"github.com/stopyellingatme/spinup/kit/x/apikeys\"\n\n")
	out.WriteString("// Config is the [apikeys] table of spinup.toml. Change the table and run spinup g apikeys.\n")
	fmt.Fprintf(&out, "var Config = kitapikeys.Config{\nPrefix: %q,\nDefaultPlan: %q,\nMaxKeys: %d,\nPlans: map[string]kitapikeys.Plan{\n", d.Prefix, d.DefaultPlan, d.MaxKeys)
	for _, name := range d.PlanNames() {
		plan := d.Plans[name]
		fmt.Fprintf(&out, "%q: {PerMinute: %d, PerDay: %d},\n", name, plan.PerMinute, plan.PerDay)
	}
	out.WriteString("},\n}\n")
	data, err := format.Source([]byte(out.String()))
	if err != nil {
		panic(err)
	}
	return data
}

// RenderAPIKeysTSFile returns the TypeScript source of web/src/lib/apikeys.gen.ts.
func RenderAPIKeysTSFile(_ APIKeysDecl, r AuthRoles) []byte {
	return []byte("// Code generated by spinup. DO NOT EDIT.\n\n/** The role that opens /admin/apikeys ([auth] admin_role in spinup.toml). */\nexport const adminRole = '" + r.Admin + "';\n")
}

// checkAPIKeysFields rejects a key in [apikeys] or in a plan table that ADR 0030
// decision 2 does not define. It reads the raw TOML in sorted order.
func checkAPIKeysFields(raw any) error {
	if raw == nil {
		return nil
	}
	table, ok := raw.(map[string]any)
	if !ok {
		return fmt.Errorf("apikeys: [apikeys] must be a table%s", apiKeysHint)
	}
	for _, field := range sortedKeys(table) {
		switch field {
		case "prefix", "default_plan", "max_keys":
		case "plans":
			plans, ok := table[field].(map[string]any)
			if !ok {
				return fmt.Errorf("apikeys: [apikeys.plans] must be a table of plan tables%s", apiKeysHint)
			}
			for _, name := range sortedKeys(plans) {
				plan, ok := plans[name].(map[string]any)
				if !ok {
					return fmt.Errorf("apikeys: [apikeys.plans.%s] must be a table%s", name, apiKeysHint)
				}
				for _, key := range sortedKeys(plan) {
					if key != "per_minute" && key != "per_day" {
						return fmt.Errorf("apikeys: plan %q: unknown key %q (allowed: per_minute, per_day)%s", name, key, apiKeysHint)
					}
				}
			}
		default:
			return fmt.Errorf("apikeys: unknown key %q (allowed: prefix, default_plan, max_keys, plans)%s", field, apiKeysHint)
		}
	}
	return nil
}

func sortedKeys(m map[string]any) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	return keys
}
