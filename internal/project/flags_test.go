func TestFlagValidation(t *testing.T) {
	valid := FlagDecl{Key: "new_checkout", Description: "Checkout"}
	hint := func(key, rule string) string {
		return "flags: the key \"" + key + "\" " + rule + ".\nTry: correct [flags." + key + "] in spinup.toml and run spinup g flags."
	}
	tests := []struct {
		name  string
		flags FlagDecls
		want  string
	}{
		{"valid", FlagDecls{valid}, ""},
		{"count", make(FlagDecls, 65), "flags: count 65 must be 0 to 64.\nTry: correct [flags] in spinup.toml and run spinup g flags."},
		{"key", FlagDecls{{Key: "New", Description: "x"}}, hint("New", "does not match ^[a-z][a-z0-9_]{0,47}$")},
		{"double underscore", FlagDecls{{Key: "a__b", Description: "x"}}, hint("a__b", "must have no double underscore")},
		{"trailing underscore", FlagDecls{{Key: "a_", Description: "x"}}, hint("a_", "must have no trailing underscore")},
		{"empty description", FlagDecls{{Key: "a"}}, hint("a", "must have a description of 1 to 200 characters with no line break")},
		{"long description", FlagDecls{{Key: "a", Description: strings.Repeat("a", 201)}}, hint("a", "must have a description of 1 to 200 characters with no line break")},
		{"description newline", FlagDecls{{Key: "a", Description: "x\ny"}}, hint("a", "must have a description of 1 to 200 characters with no line break")},
		{"owner", FlagDecls{{Key: "a", Description: "x", Owner: strings.Repeat("a", 255)}}, hint("a", "must have an owner of at most 254 characters with no line break")},
		{"expiry", FlagDecls{{Key: "a", Description: "x", Expires: "2026-02-30"}}, hint("a", "must have an expires date in YYYY-MM-DD format")},
		{"reserved", FlagDecls{{Key: "set", Description: "x"}}, hint("set", "has reserved FlagConst value Set")},
		{"collision", FlagDecls{{Key: "a1", Description: "x"}, {Key: "a_1", Description: "x"}}, hint("a_1", "has the same FlagConst value \"A1\" as \"a1\"")},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := tt.flags.Validate()
			got := ""
			if err != nil {
				got = err.Error()
			}
			if got != tt.want {
				t.Fatalf("error = %q, want %q", got, tt.want)
			}
		})
	}
}

func TestParseUnknownFlagField(t *testing.T) {
	_, err := Parse([]byte("[flags.demo]\ndescription = \"Demo\"\nunknown = true\n"))
	want := "flag \"demo\": unknown key \"unknown\" (allowed: description, default, public, owner, expires)\nTry: correct [flags.demo] in spinup.toml and run spinup g flags."
	if err == nil || err.Error() != want {
		t.Fatalf("error = %v, want %q", err, want)
	}

}
func TestFlagRenders(t *testing.T) {
	for _, tc := range []struct {
		path string
		got  []byte
	}{
		{"api/internal/flags/flags.gen.go", RenderFlagsFile(nil)},
		{"web/src/lib/flags.gen.ts", RenderFlagsTSFile(nil, (&Config{}).AuthRoles())},
	} {
		want, err := os.ReadFile(filepath.Join("..", "templates", "packs", "flags", "files", filepath.FromSlash(tc.path)))
		if err != nil {
			t.Fatal(err)
		}
		if string(tc.got) != string(want) {
			t.Fatalf("%s differs", tc.path)
		}
	}
	d := FlagDecls{{Key: "new_checkout", Description: "The new checkout flow", Public: true, Expires: "2027-03-31"}}
	want := `// Code generated by spinup. DO NOT EDIT.

package flags

import kitflags "github.com/stopyellingatme/spinup/kit/x/flags"

const (
	// NewCheckout is the "new_checkout" flag.
	NewCheckout = "new_checkout"
)

// Set is the flag set of this app. Pass it to flags.WithDeclared.
var Set = kitflags.Declared{
	NewCheckout: {Description: "The new checkout flow", Default: false, Public: true, Expires: "2027-03-31"},
}
`
	if got := string(RenderFlagsFile(d)); got != want {
		t.Fatalf("got %s", got)
	}
	if got := string(RenderFlagsTSFile(d, (&Config{}).AuthRoles())); !strings.Contains(got, "export type FlagKey = 'new_checkout';") {
		t.Fatal(got)
	}
}

