package project

import (
	"slices"
	"time"
)

// Paths of the files that spinup g flags writes (ADR 0029 decision 3).
const (
	FlagsFilePath   = "api/internal/flags/flags.gen.go"
	FlagsTSFilePath = "web/src/lib/flags.gen.ts"
)

// FlagDecl is one [flags.<key>] table of spinup.toml.
type FlagDecl struct {
	Key         string `toml:"-"`
	Description string `toml:"description"`
	Default     bool   `toml:"default"`
	Public      bool   `toml:"public"`
	Owner       string `toml:"owner"`
	Expires     string `toml:"expires"`
}

// FlagDecls is the declared flags in key order.
type FlagDecls []FlagDecl

// FlagDecls returns the declared flags sorted by key, with Key filled from the
// map key.
func (c *Config) FlagDecls() FlagDecls {
	decls := make(FlagDecls, 0, len(c.Flags))
	for key, decl := range c.Flags {
		decl.Key = key
		decls = append(decls, decl)
	}
	slices.SortFunc(decls, func(a, b FlagDecl) int {
		switch {
		case a.Key < b.Key:
			return -1
		case a.Key > b.Key:
			return 1
		}
		return 0
	})
	return decls
}

// Validate checks the rules of ADR 0029 decision 2.3. Unit F1 implements it.
func (d FlagDecls) Validate() error {
	return nil
}

// ExpiresOn returns the parsed expires date. ok is false when it is empty or
// does not parse.
func (d FlagDecl) ExpiresOn() (time.Time, bool) {
	if d.Expires == "" {
		return time.Time{}, false
	}
	t, err := time.Parse(time.DateOnly, d.Expires)
	return t, err == nil
}

// FlagConst converts a flag key such as new_checkout to NewCheckout.
func FlagConst(key string) string {
	return RoleConst(key)
}

// RenderFlagsFile returns the Go source of api/internal/flags/flags.gen.go.
// Unit F1 implements it. The stub returns the zero-flag file.
func RenderFlagsFile(d FlagDecls) []byte {
	return []byte(defaultFlagsFile)
}

// RenderFlagsTSFile returns the source of web/src/lib/flags.gen.ts. Unit F1
// implements it. The stub returns the zero-flag file.
func RenderFlagsTSFile(d FlagDecls, r AuthRoles) []byte {
	return []byte(defaultFlagsTSFile)
}

const defaultFlagsFile = `// Code generated by spinup. DO NOT EDIT.

package flags

import kitflags "github.com/stopyellingatme/spinup/kit/x/flags"

// No flags are declared. Add a [flags.<key>] table to spinup.toml and run spinup g flags.
var Set = kitflags.Declared{}
`

