// FlagDecl is one [flags.<key>] table of spinup.toml.
type FlagDecl struct {
	Key         string `toml:"-"`
	Description string `toml:"description"`
	Default     bool   `toml:"default"`
	Public      bool   `toml:"public"`
	Owner       string `toml:"owner"`
	Expires     string `toml:"expires"`
}

// FlagDecls is the declared flags in key order.
type FlagDecls []FlagDecl

// FlagDecls returns the declared flags sorted by key, with Key filled from the
// map key.
func (c *Config) FlagDecls() FlagDecls {
	decls := make(FlagDecls, 0, len(c.Flags))
	for key, decl := range c.Flags {
		decl.Key = key
		decls = append(decls, decl)
	}
	slices.SortFunc(decls, func(a, b FlagDecl) int {
		switch {
		case a.Key < b.Key:
			return -1
		case a.Key > b.Key:
			return 1
		}
		return 0
	})
	return decls
}

var flagKeyPattern = regexp.MustCompile(`^[a-z][a-z0-9_]{0,47}$`)

// Validate checks the rules of ADR 0029 decision 2.3.
func (d FlagDecls) Validate() error {
	if len(d) > 64 {
		return fmt.Errorf("flags: count %d must be 0 to 64.%s", len(d), "\nTry: correct [flags] in spinup.toml and run spinup g flags.")
	}
	constants := make(map[string]string)
	for _, f := range d {
		hint := fmt.Sprintf("\nTry: correct [flags.%s] in spinup.toml and run spinup g flags.", f.Key)
		fail := func(rule string) error { return fmt.Errorf("flags: the key %q %s.%s", f.Key, rule, hint) }
		switch {
		case !flagKeyPattern.MatchString(f.Key):
			return fail("does not match " + flagKeyPattern.String())
		case strings.Contains(f.Key, "__"):
			return fail("must have no double underscore")
		case strings.HasSuffix(f.Key, "_"):
			return fail("must have no trailing underscore")
		case utf8.RuneCountInString(f.Description) < 1 || utf8.RuneCountInString(f.Description) > 200 || strings.ContainsAny(f.Description, "\r\n"):
			return fail("must have a description of 1 to 200 characters with no line break")
		case utf8.RuneCountInString(f.Owner) > 254 || strings.ContainsAny(f.Owner, "\r\n"):
			return fail("must have an owner of at most 254 characters with no line break")
		}
		if f.Expires != "" {
			if _, ok := f.ExpiresOn(); !ok {
				return fail("must have an expires date in YYYY-MM-DD format")
			}
		}
		c := FlagConst(f.Key)
		if c == "Set" {
			return fail("has reserved FlagConst value Set")
		}
		if prev, ok := constants[c]; ok {
			return fail(fmt.Sprintf("has the same FlagConst value %q as %q", c, prev))
		}
		constants[c] = f.Key
	}
	return nil
}

// ExpiresOn returns the parsed expires date. ok is false when it is empty or
// does not parse.
func (d FlagDecl) ExpiresOn() (time.Time, bool) {
	if d.Expires == "" {
		return time.Time{}, false
	}
	t, err := time.Parse(time.DateOnly, d.Expires)
	return t, err == nil
}

// FlagConst converts a flag key such as new_checkout to NewCheckout.
func FlagConst(key string) string {
	return RoleConst(key)
}

// RenderFlagsFile returns the formatted Go source for the declared flags.
func RenderFlagsFile(d FlagDecls) []byte {
	if err := d.Validate(); err != nil {
		panic(err)
	}
	d = slices.Clone(d)
	slices.SortFunc(d, func(a, b FlagDecl) int { return strings.Compare(a.Key, b.Key) })
	var out strings.Builder
	out.WriteString("// Code generated by spinup. DO NOT EDIT.\n\npackage flags\n\nimport kitflags \"github.com/stopyellingatme/spinup/kit/x/flags\"\n\n")
	if len(d) == 0 {
		out.WriteString("// No flags are declared. Add a [flags.<key>] table to spinup.toml and run spinup g flags.\nvar Set = kitflags.Declared{}\n")
	} else {
		out.WriteString("const (\n")
		for _, f := range d {
			fmt.Fprintf(&out, "// %s is the %q flag.\n%s = %q\n", FlagConst(f.Key), f.Key, FlagConst(f.Key), f.Key)
		}
		out.WriteString(")\n\n// Set is the flag set of this app. Pass it to flags.WithDeclared.\nvar Set = kitflags.Declared{\n")
		for _, f := range d {
			fmt.Fprintf(&out, "%s: {Description: %q, Default: %t, Public: %t, Expires: %q},\n", FlagConst(f.Key), f.Description, f.Default, f.Public, f.Expires)
		}
		out.WriteString("}\n")
	}
	data, err := format.Source([]byte(out.String()))
	if err != nil {
		panic(err)
	}
	return data
}

// RenderFlagsTSFile returns the TypeScript source for the public flags and admin role.
func RenderFlagsTSFile(d FlagDecls, r AuthRoles) []byte {
	d = slices.Clone(d)
	slices.SortFunc(d, func(a, b FlagDecl) int { return strings.Compare(a.Key, b.Key) })
	var keys []string
	for _, f := range d {
		if f.Public {
			keys = append(keys, "'"+f.Key+"'")
		}
	}
	union := "never"
	if len(keys) > 0 {
		union = strings.Join(keys, " | ")
	}
	return []byte("// Code generated by spinup. DO NOT EDIT.\n/** The public flag keys of this app. */\nexport type FlagKey = " + union + ";\n/** The role that can open /admin/flags (admin_role in spinup.toml). */\nexport const adminRole = '" + r.Admin + "';\n")
}

// checkFlagFields rejects a key in a [flags.<key>] table that ADR 0029
// decision 2.2 does not define. It reads the raw TOML in sorted order.
func checkFlagFields(raw any) error {
	tables, ok := raw.(map[string]any)
	if !ok {
		return nil
	}
	keys := make([]string, 0, len(tables))
	for key := range tables {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	for _, key := range keys {
		table, ok := tables[key].(map[string]any)
		if !ok {
			return fmt.Errorf("flag %q: [flags.%s] must be a table%s", key, key, fmt.Sprintf("\nTry: correct [flags.%s] in spinup.toml and run spinup g flags.", key))
		}
		fields := make([]string, 0, len(table))
		for field := range table {
			fields = append(fields, field)
		}
		slices.Sort(fields)
		for _, field := range fields {
			switch field {
			case "description", "default", "public", "owner", "expires":
			default:
				return fmt.Errorf("flag %q: unknown key %q (allowed: description, default, public, owner, expires)%s", key, field, fmt.Sprintf("\nTry: correct [flags.%s] in spinup.toml and run spinup g flags.", key))
			}
		}
	}
	return nil
}
