package project

import (
	"fmt"
	"go/format"
	"regexp"
	"slices"
	"strings"
)

// RolesFilePath is the generated role file relative to the project root.
const RolesFilePath = "api/internal/roles/roles.gen.go"

var roleNamePattern = regexp.MustCompile(`^[a-z][a-z0-9_]{0,31}$`)

// AuthRoles declares the role names and their administrator and default roles.
type AuthRoles struct {
	// Names lists the declared roles in their configured order.
	Names []string
	// Admin is the role that identifies administrators.
	Admin string
	// Default is the role for new accounts.
	Default string
}

// AuthRoles returns the configured roles with defaults for omitted values.
func (c *Config) AuthRoles() AuthRoles {
	r := AuthRoles{Names: []string{"manager", "staff"}, Admin: "manager", Default: "staff"}
	if c == nil {
		return r
	}
	if c.Auth.Roles != nil {
		r.Names = slices.Clone(c.Auth.Roles)
	}
	if c.Auth.AdminRole != "" || c.authAdminSet {
		r.Admin = c.Auth.AdminRole
	}
	if c.Auth.DefaultRole != "" || c.authDefaultSet {
		r.Default = c.Auth.DefaultRole
	}
	return r
}

// Validate checks the role names, generated constants, and selected roles.
func (r AuthRoles) Validate() error {
	const hint = "\nTry: correct [auth] in spinup.toml and run spinup g roles."
	if len(r.Names) < 1 || len(r.Names) > 16 {
		return fmt.Errorf("auth roles: list length %d must be 1 to 16.%s", len(r.Names), hint)
	}
	names, constants := make(map[string]bool), make(map[string]string)
	for _, name := range r.Names {
		if !roleNamePattern.MatchString(name) {
			return fmt.Errorf("auth role %q must match %s.%s", name, roleNamePattern.String(), hint)
		}
		if strings.Contains(name, "__") {
			return fmt.Errorf("auth role %q must have no double underscore.%s", name, hint)
		}
		if strings.HasSuffix(name, "_") {
			return fmt.Errorf("auth role %q must have no trailing underscore.%s", name, hint)
		}
		if names[name] {
			return fmt.Errorf("auth role %q is repeated: names must be unique.%s", name, hint)
		}
		names[name] = true
		constant := RoleConst(name)
		if constant == "Set" {
			return fmt.Errorf("auth role %q has reserved RoleConst value Set.%s", name, hint)
		}
		if previous, exists := constants[constant]; exists {
			return fmt.Errorf("auth roles %q and %q have the same RoleConst value %q.%s", previous, name, constant, hint)
		}
		constants[constant] = name
	}
	if !names[r.Admin] {
		return fmt.Errorf("auth admin_role %q must be in roles.%s", r.Admin, hint)
	}
	if !names[r.Default] {
		return fmt.Errorf("auth default_role %q must be in roles.%s", r.Default, hint)
	}
	return nil
}

// RoleConst converts a role name such as front_desk to FrontDesk.
func RoleConst(name string) string {
	var out strings.Builder
	for _, part := range strings.Split(name, "_") {
		if part != "" {
			out.WriteString(strings.ToUpper(part[:1]))
			out.WriteString(part[1:])
		}
	}
	return out.String()
}

// RenderRolesFile returns the formatted Go source for a validated role set.
func RenderRolesFile(r AuthRoles) []byte {
	var out strings.Builder
	out.WriteString("// Code generated by spinup. DO NOT EDIT.\n\npackage roles\n\nimport \"github.com/stopyellingatme/spinup/kit/auth\"\n\nconst (\n")
	constants := make([]string, 0, len(r.Names))
	for _, name := range r.Names {
		constant := RoleConst(name)
		fmt.Fprintf(&out, "// %s is the %q role.\n%s = %q\n", constant, name, constant, name)
		constants = append(constants, constant)
	}
	out.WriteString(")\n\n// Set is the role set of this app. Pass it to auth.WithRoles.\n")
	fmt.Fprintf(&out, "var Set = auth.Roles{Names: []string{%s}, Admin: %s, Default: %s}\n", strings.Join(constants, ", "), RoleConst(r.Admin), RoleConst(r.Default))
	data, err := format.Source([]byte(out.String()))
	if err != nil {
		panic(fmt.Sprintf("render roles file: invalid role set: %v\nTry: validate the role set before rendering.", err))
	}
	return data
}
